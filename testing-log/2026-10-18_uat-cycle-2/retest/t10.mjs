import { open, BASE } from "./ui.mjs"; import { rec, sql } from "./h.mjs";
const [w,h,tag] = process.argv[2]==="d" ? [1280,800,"1280"] : [390,844,"390"];
const PID="bc20f19b-264a-4675-a30f-6a71c487b664";
const { browser, page, shot } = await open("manager", w, h);
await page.goto(BASE + "/projects/" + PID, { waitUntil: "domcontentloaded" }); await page.waitForTimeout(12000);
await shot(`t10-${tag}-01-project`);
const btns = await page.getByRole("button").evaluateAll((e)=>e.map(x=>x.textContent.trim()).filter(Boolean));
console.log(btns.join(" | "));
const edit = page.getByRole("button", { name: /^Edit/ }).locator("visible=true").first();
await edit.click(); await page.waitForTimeout(2000);
await shot(`t10-${tag}-02-edit`);
const code = page.getByLabel(/^Code/i).first();
rec(`t10-${tag}-code-before`, await code.inputValue());
await code.fill("");
const resp = page.waitForResponse((r)=>r.url().includes("/api/projects/")&&r.request().method()==="PATCH",{timeout:15000}).catch(()=>null);
await page.getByRole("button", { name: /^Save/ }).locator("visible=true").last().click();
const r = await resp;
await page.waitForTimeout(2500);
rec(`t10-${tag}`, { patchStatus: r?.status(), body: r ? (await r.text()).slice(0,200) : null, dbCode: sql(`select coalesce(code,'<null>') from projects where id='${PID}'`) });
await shot(`t10-${tag}-03-saved`);
await browser.close();
