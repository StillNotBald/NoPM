import { open, BASE } from "./ui.mjs"; import { rec, sql } from "./h.mjs";
const [w,h,tag] = process.argv[2]==="d" ? [1280,800,"1280"] : [390,844,"390"];
const { browser, page, shot, text } = await open("manager", w, h);
await page.goto(BASE + "/change-control", { waitUntil: "domcontentloaded" }); await page.waitForTimeout(4000);
await page.getByRole("button", { name: /Raise Change Request/ }).first().click(); await page.waitForTimeout(800);
const title = `T3 retest emergency ${tag}`;
await page.getByPlaceholder("Change request title").fill(title);
await page.getByLabel(/Emergency: commit now/).check();
await shot(`t3-${tag}-02-form-ticked`);
await page.getByRole("button", { name: /^Raise Change Request$/ }).last().click();
await page.waitForTimeout(4000);
await shot(`t3-${tag}-03-after-submit`);
const id = sql(`select id from change_requests where title='${title}' order by created_at desc limit 1`);
rec(`t3-${tag}-id`, id);
await page.goto(BASE + "/change-control?cr=" + id, { waitUntil: "domcontentloaded" }); await page.waitForTimeout(4000);
const t = await text();
rec(`t3-${tag}-page-has`, { note: /Emergency change: committed without approval on .* by /.test(t), badge: /Emergency/.test(t), approve: /\bApprove\b/.test(t), reject: /\bReject\b/.test(t), defer: /\bDefer\b/.test(t), url: page.url() });
await shot(`t3-${tag}-04-detail`);
console.log(t.slice(0, 900));
await browser.close();
